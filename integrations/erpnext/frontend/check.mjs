assert.throws(() => assertCurrentForm(page, { ...page, name: 'C2' }, form));
assert.throws(() => assertCurrentForm(page, page, null));
assert.throws(() => assertCurrentForm(page, page, { ...form, doc: { ...form.doc, docstatus: 1 } }));
console.log('SSE fragmentation, message reduction, and stale/unsupported/submitted form checks passed');

