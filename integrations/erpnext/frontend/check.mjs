import assert from 'node:assert/strict';
import { sseParser, reduceEvent, assertCurrentForm } from './protocol.mjs';
const events = [];
const parse = sseParser((event, id) => events.push([event, id]));
parse('id: 7\r\ndata: {"type":"TEXT_MESSAGE_START","messageId":"a"}\r');
parse('\n\r\ndata: {"type":"TEXT_MESSAGE_CONTENT",\r\ndata: "messageId":"a","delta":"你好"}\r\n\r\n');
parse('data: {"type":"TEXT_MESSAGE_END","messageId":"a"}', true);
assert.equal(events.length, 3);
assert.equal(events[0][1], '7');
const state = events.reduce((state, [event]) => reduceEvent(state, event), { messages: [], status: 'running' });
assert.equal(state.messages[0].content, '你好');
assert.equal(state.messages[0].status, 'complete');
const replay = events.reduce((state, [event]) => reduceEvent(state, event), state);
assert.equal(replay.messages.length, 1);
assert.equal(replay.messages[0].content, '你好');
